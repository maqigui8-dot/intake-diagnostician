def main():
    post("/baseline", {
        "age": 32, "sex": "female", "height_cm": 165, "weight_kg": 82,
        "waist_cm": 90, "measured_at": "2026-08-18",
    })
    print("baseline done")
    post("/open-answer", {"answer": "最近半年体重增加了十斤，饭后容易犯困，想改善体重和精神状态。"})
    print("open done")

    for i in range(30):
        st = post("/analyze", {})
        phase = st.get("phase")
        nq = st.get("next_question", "")
        print(f"[{i}] phase={phase} next={nq[:40]}")
        if phase in ("completed", "incomplete", "escalated"):
            print("TERMINAL", phase, "stop_reason:", st.get("stop_reason_public"))
            break
        if not nq:
            print("no question, breaking")
            break
        ans = simulate_answer(nq)
        post("/follow-up", {"answer": ans})
        time.sleep(0.3)

    print("FINAL SESSION:", SID)


if __name__ == "__main__":
    main()
